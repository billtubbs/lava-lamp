"""
lava_lamp_sph.py
================

Python/CasADi port of the particle physics in the browser "Lava Lamp Simulator"
(https://lava-lamp-simulation.web.app/, JavaScript function ``updateParticles``).

The simulation is a simplified SPH-like particle model:

* pairwise soft repulsion  ``stiffness * (1 - q)^2``          (q = r / h)
* same-material cohesion   ``- 0.04 * st_factor``             ("surface tension")
* same-material viscosity  radial impulse damping separating pairs
* temperature stored as "mass": gravity acts as ``vy += g * m``, the heater at
  the bottom drives wax towards ``m = goal_hot`` (< 0, buoyant) and ambient
  cooling drives it back towards ``m = goal_cold`` (> 0, sinks)
* symplectic Euler with dt = 1 frame, velocity clamp, lamp-shaped polygon
  boundary (snap-back + SPH-style wall repulsion)

How CasADi is used
------------------
Neighbour search is data dependent, so it stays in NumPy/SciPy (KD-tree).
Everything numerical is generated by CasADi as two per-particle functions:

``lava_pre(s, p) -> s_pre``
    gravity + heater/ambient temperature update (no neighbours needed)

``lava_step(s, nb, mask, lower, p) -> s_next``
    neighbour interactions over a fixed number of padded neighbour slots,
    heat conduction, velocity clamp, position update, polygon boundary

Both are ``.map()``-ed over all particles.  They can be JIT-compiled
(``jit=True``) or exported as C code with :func:`generate_c`.

State layout (one column per particle): ``[x, y, vx, vy, m, mat]``
with ``mat = 0`` for water and ``mat = 1`` for wax.  Units are canvas pixels
and frames, as in the original.

Differences from the JavaScript
-------------------------------
The JS loop updates particles in place (Gauss-Seidel-like: a particle sees
velocities/positions already modified earlier in the same frame).  This port
evaluates all interactions from the start-of-step state (Jacobi), which is
what makes it expressible as a mapped, parallel CasADi function.  Every
formula and constant is otherwise taken directly from the JS.  Mouse
interaction, the debugging "balls" and the deprecated source/drain modes are
not ported.
"""

from __future__ import annotations

from dataclasses import dataclass, fields
from pathlib import Path

import casadi as ca
import numpy as np
from scipy.spatial import cKDTree

# --------------------------------------------------------------------------
# Constants hard-coded in the JavaScript
# --------------------------------------------------------------------------
STATE_NAMES = ("x", "y", "vx", "vy", "m", "mat")
NX = len(STATE_NAMES)
WATER, WAX = 0.0, 1.0

COHESION = 0.04          # pressure -= 0.04 * stFactor
WATER_ST_NUMERATOR = 2.5  # water stFactor = 2.5 / ST_RATIO
VISC_EPS = 0.01          # impulse denominator: distSq + 0.01 * H^2
HEAT_BASE = 0.002        # heater rate at the centre line
HEAT_FALLOFF = 0.0015    # rate reduction towards the side walls
WALL_WAX_FACTOR = 1.25   # wax is pushed harder by the walls
NORMAL_EPS = 1e-7        # wall-distance threshold for the fallback normal
BIG = 1e30


@dataclass
class LavaParams:
    """Run-time parameters (passed to the CasADi functions as a vector)."""

    gravity: float = 0.1
    h: float = 17.0              # interaction (smoothing) radius [px]
    stiffness: float = 2.5       # pair repulsion strength
    visc_water: float = 0.3      # VISCOSITY (water-water pairs)
    visc_wax: float = 0.3        # particle.viscosity of wax (= VISCOSITY at init)
    st_ratio: float = 2.5        # "Surface Tension" slider
    temp_speed: float = 1.0      # "Heat Transfer" slider
    max_vel: float = 4.0         # velocity clamp [px/frame]
    goal_hot: float = -6.0       # "mass" wax relaxes to on the heater
    goal_cold: float = 1.0       # "mass" wax relaxes to through ambient cooling
    ambient_rate: float = 0.25
    cond_rate: float = 1e-5      # wax-wax conduction rate
    heater_height: float = 10.0  # heater zone thickness above the bottom [px]

    def vector(self) -> np.ndarray:
        return np.array([float(getattr(self, f.name)) for f in fields(self)])


PARAM_NAMES = tuple(f.name for f in fields(LavaParams))
NP = len(PARAM_NAMES)


def _unpack(p: ca.SX) -> dict:
    return {name: p[i] for i, name in enumerate(PARAM_NAMES)}


# --------------------------------------------------------------------------
# Geometry
# --------------------------------------------------------------------------
def lamp_polygon(width: float = 400.0, height: float = 600.0) -> np.ndarray:
    """The lamp outline used in the original (BORDER_POLY), shape (n, 2)."""
    top, mid, bot = 175 / 1.25, 340 / 1.25, 280 / 1.25
    cx, ym = width / 2, 0.8 * height
    return np.array([
        [cx - top / 2, 0.0],
        [cx + top / 2, 0.0],
        [cx + mid / 2, ym],
        [cx + bot / 2, height],
        [cx - bot / 2, height],
        [cx - mid / 2, ym],
    ])


def initial_state(n: int = 3000, wax_ratio: float = 0.2,
                  width: float = 400.0, height: float = 600.0,
                  seed: int | None = None) -> np.ndarray:
    """Replicates ``initParticles``: jittered grid, first ``wax_ratio`` are wax."""
    rng = np.random.default_rng(seed)
    R = height / width
    c_ideal = np.sqrt(n / R)
    c1, c2 = int(np.floor(c_ideal)), int(np.ceil(c_ideal))
    r1, r2 = int(np.ceil(n / c1)), int(np.ceil(n / c2))
    # (sic) the JS compares row counts with the aspect ratio
    if abs(r1 - R) < abs(r2 - R):
        per_row, per_col = r1, c1
    else:
        per_row, per_col = r2, c2
    i = np.arange(n)
    x = ((i % per_row) + (rng.random(n) - 0.5) / 5) * (width / per_row)
    y = ((i // per_row) + (rng.random(n) - 0.5) / 5) * (height / per_col)
    wax = i < n * wax_ratio
    s = np.zeros((NX, n))
    s[0], s[1] = x, y
    s[4] = np.where(wax, 1.5, 0.0)
    s[5] = np.where(wax, WAX, WATER)
    return s


# --------------------------------------------------------------------------
# CasADi function builders
# --------------------------------------------------------------------------
def build_pre_function(width: float = 400.0, height: float = 600.0,
                       opts: dict | None = None) -> ca.Function:
    """Gravity and heater/ambient temperature update for one particle."""
    s = ca.SX.sym("s", NX)
    p = ca.SX.sym("p", NP)
    P = _unpack(p)
    x, y, vx, vy, m, mat = ca.vertsplit(s)

    vy1 = vy + P["gravity"] * m                     # gravity uses old "mass"

    is_wax = mat > 0.5
    rate = (HEAT_BASE - ca.fabs(x - width / 2) / width * HEAT_FALLOFF) * P["temp_speed"]
    goal = ca.if_else(y > height - P["heater_height"], P["goal_hot"], m)
    m1 = m + (goal - m) * rate
    m1 = ca.if_else(m1 < P["goal_cold"], m1 + P["ambient_rate"] * rate, m1)
    m_new = ca.if_else(is_wax, m1, m)

    out = ca.vertcat(x, y, vx, vy1, m_new, mat)
    return ca.Function("lava_pre", [s, p], [out], ["s", "p"], ["s_pre"], opts or {})


def _boundary(px, py, vx, vy, is_wax, polygon: np.ndarray, h, stiffness):
    """Port of ``applyBorderForce``: snap back inside, then wall repulsion.

    The polygon is numeric (fixed at build time), so degenerate edges and the
    winding order are resolved in Python.
    """
    poly = np.asarray(polygon, dtype=float)
    nv = len(poly)
    area = sum(poly[i, 0] * poly[(i + 1) % nv, 1] - poly[(i + 1) % nv, 0] * poly[i, 1]
               for i in range(nv))
    is_ccw = area > 0

    # 1. inside test (ray casting, crossing parity)
    crossings = 0
    for i in range(nv):
        j = i - 1  # previous vertex, as in the JS loop
        (xi, yi), (xj, yj) = poly[i], poly[j]
        if yi == yj:
            continue  # horizontal edge: (yi > py) != (yj > py) is always false
        straddle = ca.ne(yi > py, yj > py)
        x_int = (xj - xi) * (py - yi) / (yj - yi) + xi
        crossings = crossings + ca.logic_and(straddle, px < x_int)
    inside = ca.fmod(crossings, 2) > 0.5

    # 2a. snap to the first wall crossing along the step p0 -> p
    p0x, p0y = px - vx, py - vy
    s1x, s1y = vx, vy
    best_t = ca.SX(BIG)
    found = ca.SX(0)
    for i in range(nv):
        a, b = poly[i], poly[(i + 1) % nv]
        s2x, s2y = b[0] - a[0], b[1] - a[1]
        denom = -s2x * s1y + s1x * s2y
        nz = ca.ne(denom, 0)
        d_safe = ca.if_else(nz, denom, 1)
        ss = (-s1y * (p0x - a[0]) + s1x * (p0y - a[1])) / d_safe
        t = (s2x * (p0y - a[1]) - s2y * (p0x - a[0])) / d_safe
        valid = nz * (ss >= 0) * (ss <= 1) * (t >= 0) * (t <= 1)
        better = ca.logic_and(valid, t < best_t)
        best_t = ca.if_else(better, t, best_t)
        found = ca.logic_or(found, valid)
    t_hit = ca.if_else(found, best_t, 0)
    hit_x, hit_y = p0x + t_hit * s1x, p0y + t_hit * s1y

    # 2b. fallback: nearest point on the outline
    best_d = ca.SX(BIG)
    snap_x, snap_y = px, py
    for i in range(nv):
        a, b = poly[i], poly[(i + 1) % nv]
        ex, ey = b[0] - a[0], b[1] - a[1]
        l2 = ex * ex + ey * ey
        if l2 == 0:
            continue
        t = ca.fmin(1, ca.fmax(0, ((px - a[0]) * ex + (py - a[1]) * ey) / l2))
        qx, qy = a[0] + t * ex, a[1] + t * ey
        d = ca.sqrt((px - qx) ** 2 + (py - qy) ** 2)
        better = d < best_d
        best_d = ca.if_else(better, d, best_d)
        snap_x = ca.if_else(better, qx, snap_x)
        snap_y = ca.if_else(better, qy, snap_y)

    xs = ca.if_else(inside, px, ca.if_else(found, hit_x, snap_x))
    ys = ca.if_else(inside, py, ca.if_else(found, hit_y, snap_y))

    # 3. SPH-style wall repulsion (changes velocity for the next step)
    wall_k = stiffness * ca.if_else(is_wax, WALL_WAX_FACTOR, 1.0)
    for i in range(nv):
        a, b = poly[i], poly[(i + 1) % nv]
        ex, ey = b[0] - a[0], b[1] - a[1]
        l2 = ex * ex + ey * ey
        if l2 == 0:
            continue
        el = np.sqrt(l2)
        n_in_x = -ey / el if is_ccw else ey / el
        n_in_y = ex / el if is_ccw else -ex / el
        t = ca.fmin(1, ca.fmax(0, ((xs - a[0]) * ex + (ys - a[1]) * ey) / l2))
        dx, dy = xs - (a[0] + t * ex), ys - (a[1] + t * ey)
        d = ca.sqrt(dx * dx + dy * dy)
        q = d / h
        f = ca.if_else(d < h, wall_k * (1 - q) ** 2, 0)
        far = d > NORMAL_EPS
        d_safe = ca.fmax(d, NORMAL_EPS)
        nx = ca.if_else(far, dx / d_safe, n_in_x)
        ny = ca.if_else(far, dy / d_safe, n_in_y)
        vx = vx + f * nx
        vy = vy + f * ny

    return xs, ys, vx, vy


def build_step_function(n_slots: int, polygon: np.ndarray | None = None,
                        opts: dict | None = None) -> ca.Function:
    """Neighbour interactions, integration and boundary for one particle.

    Inputs
    ------
    s     : (6,)          own state after ``lava_pre``
    nb    : (6*n_slots,)  neighbour states after ``lava_pre``, blocked by field:
                          [x_1..x_K, y_1..y_K, vx_..., vy_..., m_..., mat_...]
    mask  : (n_slots,)    1 for a real neighbour, 0 for padding
    lower : (n_slots,)    1 if the neighbour's index < own index (the JS only
                          applies conduction to the higher-index particle)
    p     : (NP,)         parameter vector, see :class:`LavaParams`
    """
    if polygon is None:
        polygon = lamp_polygon()
    K = n_slots
    s = ca.SX.sym("s", NX)
    nb = ca.SX.sym("nb", NX * K)
    mask = ca.SX.sym("mask", K)
    lower = ca.SX.sym("lower", K)
    p = ca.SX.sym("p", NP)
    P = _unpack(p)
    h = P["h"]

    x, y, vx, vy, m, mat = ca.vertsplit(s)
    xj, yj = nb[0:K], nb[K:2 * K]
    vxj, vyj = nb[2 * K:3 * K], nb[3 * K:4 * K]
    mj, matj = nb[4 * K:5 * K], nb[5 * K:6 * K]

    wax_i = mat > 0.5
    wax_j = matj > 0.5
    same = wax_i * wax_j + (1 - wax_i) * (1 - wax_j)

    dx, dy = x - xj, y - yj
    r2 = dx * dx + dy * dy
    active = mask * (r2 < h * h) * (r2 > 0)
    r = ca.sqrt(active * r2 + (1 - active))        # 1 in unused slots (no 0/0)
    q = r / h
    ux, uy = dx / r, dy / r

    # pressure + cohesion ("surface tension")
    st = same * ca.if_else(wax_i, P["st_ratio"], WATER_ST_NUMERATOR / P["st_ratio"])
    pressure = P["stiffness"] * (1 - q) ** 2 - COHESION * st

    # viscosity (only for separating pairs, only within one material)
    visc = same * ca.if_else(wax_i, P["visc_wax"], P["visc_water"])
    dot = (vx - vxj) * dx + (vy - vyj) * dy
    impulse = (dot > 0) * dot / (r2 + VISC_EPS * h * h) * visc * (1 - q)

    fmag = active * (pressure - impulse)
    vx1 = vx + ca.sum1(fmag * ux)
    vy1 = vy + ca.sum1(fmag * uy)

    # wax-wax heat conduction (one-sided, as in the JS)
    m1 = m + P["cond_rate"] * ca.sum1(active * lower * wax_i * wax_j * (mj - m))

    # velocity clamp
    speed = ca.sqrt(vx1 * vx1 + vy1 * vy1)
    fac = ca.if_else(speed > P["max_vel"], P["max_vel"] / ca.fmax(speed, 1e-12), 1)
    vx2, vy2 = vx1 * fac, vy1 * fac

    # integrate (dt = 1 frame) and apply the lamp boundary
    xs, ys, vx3, vy3 = _boundary(x + vx2, y + vy2, vx2, vy2, wax_i, polygon,
                                 h, P["stiffness"])

    out = ca.vertcat(xs, ys, vx3, vy3, m1, mat)
    return ca.Function("lava_step", [s, nb, mask, lower, p], [out],
                       ["s", "nb", "mask", "lower", "p"], ["s_next"], opts or {})


def jit_options(flags=("-O3", "-ffast-math")) -> dict:
    """CasADi options to JIT-compile a function with the system C compiler."""
    return {"jit": True, "compiler": "shell",
            "jit_options": {"flags": list(flags), "verbose": False}}


def generate_c(out_dir: str | Path, n_slots: int = 33,
               polygon: np.ndarray | None = None,
               width: float = 400.0, height: float = 600.0) -> Path:
    """Write ``lava_lamp.c``/``.h`` containing ``lava_pre`` and ``lava_step``."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    cg = ca.CodeGenerator("lava_lamp.c", {"with_header": True})
    cg.add(build_pre_function(width, height))
    cg.add(build_step_function(n_slots, polygon))
    cg.generate(str(out_dir) + "/")
    return out_dir / "lava_lamp.c"


# --------------------------------------------------------------------------
# Simulation driver
# --------------------------------------------------------------------------
class LavaLampSim:
    """Runs the CasADi-generated step over all particles.

    Parameters
    ----------
    n_particles, wax_ratio : initial population (defaults as in the original)
    params      : :class:`LavaParams` (can be changed between steps)
    k_max       : maximum neighbours per particle; the nearest ``k_max`` within
                  ``h`` are used (``truncated`` counts particles that hit it)
    jit         : compile the generated functions with the C compiler

    The mapped functions are called through CasADi's zero-copy
    ``Function.buffer()`` interface on preallocated NumPy arrays; converting
    the large neighbour array to a ``DM`` on every call would otherwise cost
    more than the physics itself.  Internally the state is stored as an
    (N, 6) C-contiguous array, which is the (6, N) column-major layout CasADi
    expects; ``state`` exposes the (6, N) view.
    """

    def __init__(self, n_particles: int = 3000, wax_ratio: float = 0.2,
                 params: LavaParams | None = None, width: float = 400.0,
                 height: float = 600.0, polygon: np.ndarray | None = None,
                 k_max: int = 48, jit: bool = False,
                 seed: int | None = None, state: np.ndarray | None = None):
        self.params = params or LavaParams()
        self.width, self.height = width, height
        self.polygon = lamp_polygon(width, height) if polygon is None else np.asarray(polygon)
        self.k_max = k_max
        self.n_slots = k_max + 1          # +1 because the KD-tree returns self
        s0 = (initial_state(n_particles, wax_ratio, width, height, seed)
              if state is None else np.asarray(state, dtype=float))
        self.n = n = s0.shape[1]
        K = self.n_slots
        opts = jit_options() if jit else {}
        self.pre_fn = build_pre_function(width, height, opts)
        self.step_fn = build_step_function(K, self.polygon, opts)
        # map over particles; the parameter vector is shared (reduce_in)
        self.pre_map = self.pre_fn.map("lava_pre_map", "serial", n, [1], [])
        self.step_map = self.step_fn.map("lava_step_map", "serial", n, [4], [])

        # preallocated, column-major-compatible buffers
        self._s = np.ascontiguousarray(s0.T)               # (N, 6)
        self._s_pre = np.empty((n, NX))
        self._nb = np.empty((n, NX * K))
        self._mask = np.empty((n, K))
        self._lower = np.empty((n, K))
        self._p = np.empty(NP)
        self._pre_buf, self._pre_eval = self.pre_map.buffer()
        self._pre_buf.set_arg(0, memoryview(self._s))
        self._pre_buf.set_arg(1, memoryview(self._p))
        self._pre_buf.set_res(0, memoryview(self._s_pre))
        self._step_buf, self._step_eval = self.step_map.buffer()
        for i, a in enumerate((self._s_pre, self._nb, self._mask, self._lower, self._p)):
            self._step_buf.set_arg(i, memoryview(a))
        self._step_buf.set_res(0, memoryview(self._s))
        self.frame = 0
        self.truncated = 0

    @property
    def state(self) -> np.ndarray:
        """State as a (6, N) array (rows x, y, vx, vy, m, mat). A view."""
        return self._s.T

    @state.setter
    def state(self, value: np.ndarray):
        self._s[...] = np.asarray(value, dtype=float).T

    # neighbour search (positions are unchanged by lava_pre)
    def neighbours(self, pos: np.ndarray):
        tree = cKDTree(pos)
        dist, idx = tree.query(pos, k=self.n_slots,
                               distance_upper_bound=self.params.h)
        own = np.arange(self.n)[:, None]
        mask = (idx < self.n) & (idx != own)
        self.truncated = int(np.count_nonzero(np.isfinite(dist[:, -1])))
        idx = np.where(mask, idx, own)
        lower = mask & (idx < own)
        return idx, mask, lower

    def step(self, n_steps: int = 1) -> np.ndarray:
        self._p[:] = self.params.vector()
        n, K = self.n, self.n_slots
        for _ in range(n_steps):
            self._pre_eval()                                   # -> self._s_pre
            idx, mask, lower = self.neighbours(self._s_pre[:, :2])
            # neighbour states, blocked by field: (N, K, 6) -> (N, 6, K) -> (N, 6K)
            self._nb[...] = self._s_pre[idx].transpose(0, 2, 1).reshape(n, NX * K)
            self._mask[...] = mask
            self._lower[...] = lower
            self._step_eval()                                  # -> self._s
            self.frame += 1
        return self.state

    def evaluate_dm(self) -> np.ndarray:
        """One step through the ordinary (DM) call path, without updating.

        Slower; useful for checking the buffer path or for symbolic use.
        """
        p = self.params.vector()
        s_pre = self.pre_map(self.state, p).full()
        idx, mask, lower = self.neighbours(s_pre[:2].T)
        nb = s_pre[:, idx].transpose(0, 2, 1).reshape(NX * self.n_slots, self.n)
        return self.step_map(s_pre, nb, mask.T.astype(float),
                             lower.T.astype(float), p).full()

    # convenience views
    @property
    def positions(self) -> np.ndarray:
        return self.state[:2].T

    @property
    def is_wax(self) -> np.ndarray:
        return self.state[5] > 0.5

    def temperature(self) -> np.ndarray:
        """Normalised temperature used for colouring: 0 cold, 1 hot (tempData)."""
        P = self.params
        return 1.0 - (self.state[4] - P.goal_hot) / (P.goal_cold - P.goal_hot)
